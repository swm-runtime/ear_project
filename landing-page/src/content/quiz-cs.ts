export type QuizQuestion = {
  /** 문제가 다루는 키워드. 화면에는 내지 않는다 — 대본 대조·관리용이다(곧 정답인 경우가 많다). */
  keyword: string;
  /**
   * 문제 위에 다는 주제. 없으면 편 주제(`episode.title`)를 단다.
   * 상황형은 편 주제가 곧 힌트가 되는 경우가 많아, 정답을 드러내지 않는 상황 이름을 단다.
   */
  title?: string;
  /** 상황형 문제의 상황 설명. 질문(`question`) 위에 보통 굵기로 그린다. */
  situation?: string;
  question: string;
  options: readonly string[];
  /** `options`의 정답 위치(0부터). */
  answer: number;
  /** 답을 고른 뒤 보여 주는 풀이. */
  explanation: string;
  /** 출처 편. 시리즈 밖 주제(메시지 브로커)에는 없다. */
  episode?: { no: number; title: string };
};

/** 결과 화면에 레벨과 함께 그리는 그림(`app/(quiz)/quiz/cs/LevelArt.tsx`). */
